#!/usr/bin/env python3
"""Folds the engine crate (native/voltz_core/engine/src) into one module file,
native/voltz_core/voltz_engine.rs, injected into game.rs as `game::voltz_engine`.
The launcher's horizon-mixins has no [[crate]] support, and module payloads
can't use `mod x;` files or `//!`, so each file becomes an inline module."""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent / "native" / "voltz_core"
SRC = ROOT / "engine" / "src"

lib = (SRC / "lib.rs").read_text()
out = ["// GENERATED by tools/gen_engine_module.py from engine/src: edit those, not this.\n"]
for line in lib.splitlines():
    m = re.match(r"pub mod (\w+);$", line)
    if m:
        body = (SRC / f"{m.group(1)}.rs").read_text()
        body = body.replace("crate::", "super::")
        out.append(f"pub mod {m.group(1)} {{\n{body}}}\n")
    else:
        out.append(line + "\n")
text = "".join(out).replace("//!", "//")
(ROOT / "voltz_engine.rs").write_text(text)
print("wrote", ROOT / "voltz_engine.rs", len(text), "bytes")
